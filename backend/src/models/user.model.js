import mongoose, { mongo } from 'mongoose';

const userSchema = new mongoose.Schema({
    email: {
        type: String,
        required: true,
        unique: true
    },
    name: {
        type: String,
        required: true,
    },
    password: {
        type: String,
        required: true,
    },
    role: {
        type: String,
        default: "user",
        enum: ["user", "seller"]
    },
    refreshToken: {
        type: String
    }
})

export const userModel = mongoose.model('User', userSchema);